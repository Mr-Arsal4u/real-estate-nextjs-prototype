export function searchAndFilter(params: {
  q?: string | null;
  location?: string | null;
  minPrice?: string | null;
  maxPrice?: string | null;
  type?: string | null;
  bedrooms?: string | null;
}) {
  const q = (params.q ?? "").toLowerCase();
  const loc = (params.location ?? "").toLowerCase();
  const min = params.minPrice ? Number(params.minPrice) : undefined;
  const max = params.maxPrice ? Number(params.maxPrice) : undefined;
  const type = (params.type ?? "").toLowerCase();
  const beds = params.bedrooms ? Number(params.bedrooms) : undefined;

  return PROPERTIES.filter((p) => {
    if (q && !p.title.toLowerCase().includes(q)) return false;
    if (loc && !p.location.toLowerCase().includes(loc)) return false;
    if (typeof min === "number" && p.price < min) return false;
    if (typeof max === "number" && p.price > max) return false;
    if (type && p.type.toLowerCase() !== type) return false;
    if (typeof beds === "number" && p.bedrooms < beds) return false;
    return true;
  });
}
